"""Generate kb.js (the chat box's only knowledge) from the master resume and story.
Run from this folder: python3 build_kb.py   (stdlib only). Nothing else feeds the chat."""
import json, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
resume = json.loads((ROOT / "data/resume.json").read_text())
story = (ROOT / "data/story.md").read_text()
profile = json.loads((ROOT / "data/profile.json").read_text())
chunks = []
def add(section, role, text, kind="fact"):
    text = re.sub(r"\s+", " ", text).strip()
    if text:
        chunks.append({"id": len(chunks) + 1, "section": section, "role": role, "kind": kind, "text": text})
c = resume["contact"]
add("profile", "", "I am %s, a %s based in %s." % (resume["name"].title(), resume["headline"], c.get("location", "Miami, FL")))
add("profile", "", "You can reach me by email at %s, by phone at %s, or on LinkedIn at %s." % (c["email"], c["phone"], c.get("linkedin", "linkedin.com/in/psirusala")), "contact")
add("profile", "", "I have about 5 years of data engineering experience: Mindtree (2020 to 2022), Triangulum Insights (2024 to 2025) and Tech Detectives (2025 to present), with an M.S. in Cybersecurity at Florida International University in between.", "years")
add("profile", "", "I work remote or hybrid and I am open to relocation for the right role. I can start two weeks after an offer.", "availability")
add("profile", "", "I am looking for Senior Data Engineer roles, and also Cloud Data Architect, Solutions or Forward Deployed Engineer, AI platform and cloud security work.", "goals")
for cat in resume["skills"]:
    add("skills", cat["category"], "%s: %s." % (cat["category"], ", ".join(cat["items"])), "skills")
for role in resume["experience"]:
    head = "%s at %s%s, %s." % (role["title"], role["company"], (", " + role["location"]) if role.get("location") else "", role["dates"])
    add("experience", role["company"], head, "role")
    for b in role["bullets"]:
        add("experience", role["company"], "At %s: %s" % (role["company"], b), "bullet")
add("certifications", "", "Certifications: " + " and ".join(resume["certifications"]) + ".", "certs")
for ed in resume["education"]:
    add("education", ed["school"], "%s, %s%s." % (ed["degree"], ed["school"], (", " + ed["location"]) if ed.get("location") else ""), "education")
# story: every bullet under each role heading, plus the defendable-skills list
role = ""
for line in story.splitlines():
    m = re.match(r"^## (.+?)(?: — (.+?))? \((.+)\)$", line.strip())
    if m:
        role = m.group(2) or m.group(1); continue
    if line.startswith("## Skills"):
        role = "skills"; continue
    s = line.strip()
    if s.startswith("- ") and role and role != "skills":
        add("story", role, "At %s: %s" % (role, s[2:]), "story")
    elif role == "skills" and s and not s.startswith("<!--") and not s.startswith("#"):
        add("skills", "defendable", "Skills I can defend in an interview: " + s, "skills")
# JobHub, from the portfolio project copy (facts already on the site)
add("projects", "JobHub", "JobHub is a side project I built: a self-hosted job search portal in Python 3.9 standard library only, with a web UI and SQLite store, polling 1,500+ company career boards, scoring postings against USCIS H-1B sponsor data for about 60,000 employers, per-role resume tailoring reviewed by a hiring-manager agent, parallel Claude browser agents that fill application forms in Chrome, Gmail integration for replies, and a janitor and retry loop.", "project")
out = "/* kb.js - generated by build_kb.py from the master resume and story. The chat box answers ONLY from this. */\nwindow.PORTFOLIO_KB = " + json.dumps(chunks, ensure_ascii=False, indent=1) + ";\n"
pathlib.Path(__file__).with_name("kb.js").write_text(out)
print("kb.js:", len(chunks), "chunks,", len(out), "bytes")
